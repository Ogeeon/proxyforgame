#!/usr/bin/env node
// @ts-check

/**
 * Generates one TypeScript project per calculator into tsconfig/.
 *
 * Why per calculator: the browser code is plain <script> globals, and a page
 * loads exactly one calculator. A single project covering www/** puts every
 * orchestrator in the same global scope, so seven `const options` declarations
 * collide - and, worse, a file that does not declare its own `options` silently
 * resolves the name to another calculator's, which produces type errors that
 * are wrong rather than useful.
 *
 * The file list per project is read from the calculator's .tpl, so the projects
 * follow whatever the page actually loads. Run it after adding or reordering a
 * <script> tag; `npm run typecheck` fails on a stale project anyway, because a
 * missing global shows up as TS2304.
 *
 * Run: node scripts/generate-tsconfigs.js [--check]
 *   --check  verify the files on disk match what would be generated, and exit
 *            non-zero if they do not. Used by CI.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const CALC_DIR = path.join(ROOT, 'www', 'ogame', 'calc');
const OUT_DIR = path.join(ROOT, 'tsconfig');

// Loaded by sidebar_bs.tpl, which every calculator page includes.
const SIDEBAR_SCRIPT = 'www/js/sidebar_bs.js';
// Ambient declarations: page globals from PHP, expando properties, bootstrap.
const AMBIENT = 'www/ogame/calc/js/globals.d.ts';
// Stand-in for calculators that declare `options` in an inline <script> in the
// template rather than in a .js file. Only added where no script declares it -
// otherwise it would collide with the real declaration.
const OPTIONS_AMBIENT = 'www/ogame/calc/js/options-global.d.ts';

/**
 * The scripts a calculator template loads, in load order.
 * @param {string} tplPath
 * @returns {string[]} paths relative to the repo root
 */
function scriptsOf(tplPath) {
  const tpl = fs.readFileSync(tplPath, 'utf8');
  const found = [...tpl.matchAll(/src="\/([^"?]+\.js)/g)].map((m) => `www/${m[1]}`);
  const includesSidebar = tpl.includes('sidebar_bs.tpl');
  const files = [...found];
  if (includesSidebar && !files.includes(SIDEBAR_SCRIPT)) {
    files.push(SIDEBAR_SCRIPT);
  }
  files.push(AMBIENT);

  const declaresOptions = files.some((f) => {
    const full = path.join(ROOT, f);
    return f.endsWith('.js')
      && fs.existsSync(full)
      && /^\s*(?:const|let|var) options\b/m.test(fs.readFileSync(full, 'utf8'));
  });
  if (!declaresOptions) files.push(OPTIONS_AMBIENT);

  return files;
}

/**
 * @param {string} calc
 * @param {string[]} files
 * @returns {string}
 */
function render(calc, files) {
  const body = {
    extends: '../tsconfig.base.json',
    files: files.map((f) => `../${f}`),
  };
  return [
    '// Generated by scripts/generate-tsconfigs.js - do not edit by hand.',
    `// The scripts ${calc}.tpl loads, and nothing else: one page, one project.`,
    JSON.stringify(body, null, 2),
    '',
  ].join('\n');
}

function main() {
  const checkOnly = process.argv.includes('--check');
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const templates = fs.readdirSync(CALC_DIR).filter((f) => f.endsWith('.tpl'));
  const stale = [];
  const written = [];

  for (const tpl of templates) {
    const calc = path.basename(tpl, '.tpl');
    const files = scriptsOf(path.join(CALC_DIR, tpl));
    // A template with no scripts of its own is a fragment, not a page.
    if (files.length <= 1) continue;

    const target = path.join(OUT_DIR, `${calc}.json`);
    const content = render(calc, files);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;

    if (current === content) continue;
    if (checkOnly) {
      stale.push(path.relative(ROOT, target));
      continue;
    }
    fs.writeFileSync(target, content);
    written.push(`${calc} (${files.length} files)`);
  }

  if (checkOnly) {
    if (stale.length) {
      console.error('Out of date, run `npm run generate-tsconfigs`:');
      for (const f of stale) console.error(`  ${f}`);
      process.exit(1);
    }
    console.log('tsconfig projects are up to date.');
    return;
  }

  console.log(written.length ? `Wrote:\n  ${written.join('\n  ')}` : 'Already up to date.');
}

main();
