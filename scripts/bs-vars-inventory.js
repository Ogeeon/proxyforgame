#!/usr/bin/env node

/**
 * Inventory of the Bootstrap CSS custom properties (`--bs-*`) the site's own
 * stylesheets use - the input to the Bootstrap 6 migration, which renames and
 * restructures them. See docs/bootstrap-6-migration.md.
 *
 * Two axes per variable:
 *   - use:  *read* (`var(--bs-x)`) or *override* (`--bs-x:` declared in our CSS,
 *           which retunes Bootstrap's own rules - common.css does this for the
 *           theme and the tooltip skin);
 *   - kind: *theme* (a public colour/shape token on :root or [data-bs-theme]),
 *           *component* (a variable scoped to one component, `--bs-tooltip-*`,
 *           `--bs-btn-*`, ...), or *internal* (something the markup of the
 *           bundle relies on rather than a documented knob: the `-rgb`
 *           triplets v6 removes, and the tooltip arrow geometry our arrow skin
 *           copies).
 *
 * Comments are stripped before scanning, so a `--bs-btn-*` in prose is not a use.
 *
 * Run: node scripts/bs-vars-inventory.js [--write | --check]
 *   (none)   print the Markdown inventory
 *   --write  replace the generated block in docs/bootstrap-6-migration.md
 *   --check  exit non-zero if that block is out of date
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const WWW = path.join(ROOT, 'www');
const DOC = path.join(ROOT, 'docs', 'bootstrap-6-migration.md');
const START = '<!-- bs-vars-inventory:start - generated by scripts/bs-vars-inventory.js, do not edit -->';
const END = '<!-- bs-vars-inventory:end -->';

const COMPONENTS = [
  'accordion', 'alert', 'badge', 'breadcrumb', 'btn', 'card', 'carousel', 'dropdown',
  'form-check', 'form-control', 'form-range', 'form-select', 'form-switch', 'list-group',
  'modal', 'nav', 'navbar', 'offcanvas', 'pagination', 'popover', 'progress', 'spinner',
  'table', 'toast', 'tooltip',
];

/** @param {string} dir @returns {string[]} */
function cssFiles(dir) {
  /** @type {string[]} */
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== 'vendor') out.push(...cssFiles(full));
    } else if (entry.name.endsWith('.css')) {
      out.push(full);
    }
  }
  return out.sort((a, b) => a.localeCompare(b));
}

/** @param {string} name without the leading `--bs-` */
function kindOf(name) {
  if (name.endsWith('-rgb') || name.startsWith('tooltip-arrow-')) return 'internal';
  if (COMPONENTS.some((c) => name === c || name.startsWith(c + '-'))) return 'component';
  return 'theme';
}

function collect() {
  /** @type {Map<string, {reads: number, overrides: number, files: Set<string>}>} */
  const vars = new Map();
  /** @type {Array<{file: string, reads: number, overrides: number}>} */
  const perFile = [];
  for (const file of cssFiles(WWW)) {
    const rel = path.relative(ROOT, file).split(path.sep).join('/');
    const css = fs.readFileSync(file, 'utf8').replaceAll(/\/\*[\s\S]*?\*\//g, '');
    let reads = 0;
    let overrides = 0;
    for (const m of css.matchAll(/--bs-([a-z0-9-]+)(\s*:)?/g)) {
      const entry = vars.get(m[1]) ?? { reads: 0, overrides: 0, files: new Set() };
      if (m[2]) {
        entry.overrides++;
        overrides++;
      } else {
        entry.reads++;
        reads++;
      }
      entry.files.add(path.basename(rel));
      vars.set(m[1], entry);
    }
    if (reads + overrides > 0) perFile.push({ file: rel, reads, overrides });
  }
  return { vars, perFile };
}

function render() {
  const { vars, perFile } = collect();
  const total = perFile.reduce((n, f) => n + f.reads + f.overrides, 0);
  const lines = [
    `${total} uses in ${perFile.length} files.`,
    '',
    '| File | Reads | Overrides |',
    '|---|---:|---:|',
    ...perFile.map((f) => `| \`${f.file}\` | ${f.reads} | ${f.overrides} |`),
    '',
    '| Variable | Kind | Reads | Overrides | Files |',
    '|---|---|---:|---:|---|',
  ];
  const order = { internal: 0, component: 1, theme: 2 };
  const rows = [...vars.entries()].sort(([a], [b]) =>
    order[kindOf(a)] - order[kindOf(b)] || a.localeCompare(b));
  for (const [name, v] of rows) {
    lines.push(`| \`--bs-${name}\` | ${kindOf(name)} | ${v.reads} | ${v.overrides} | ${[...v.files].sort((a, b) => a.localeCompare(b)).join(', ')} |`);
  }
  return lines.join('\n');
}

function main() {
  const table = render();
  const write = process.argv.includes('--write');
  const check = process.argv.includes('--check');
  if (!write && !check) {
    console.log(table);
    return;
  }
  const doc = fs.readFileSync(DOC, 'utf8');
  const from = doc.indexOf(START);
  const to = doc.indexOf(END);
  if (from < 0 || to < from) {
    console.error(`${path.relative(ROOT, DOC)} has no generated block to update.`);
    process.exit(1);
  }
  const updated = doc.slice(0, from + START.length) + '\n' + table + '\n' + doc.slice(to);
  if (check) {
    if (updated !== doc) {
      console.error('The --bs-* inventory is out of date: run `node scripts/bs-vars-inventory.js --write`.');
      process.exit(1);
    }
    console.log('The --bs-* inventory is up to date.');
    return;
  }
  fs.writeFileSync(DOC, updated);
  console.log(`Updated ${path.relative(ROOT, DOC)}.`);
}

main();
